class AcademicsScreen extends StatelessWidget {
  const AcademicsScreen({super.key});

  @override
  Widget build(BuildContext context) {
    final p = context.watch<ParentProvider>();
    final rc = p.report;
    final child = p.child;

    return Column(
      children: [
        ParentPageHeader(title: 'Academics', badge: p.term?.label),
        Expanded(
          child: ListView(
            padding: const EdgeInsets.fromLTRB(20, 0, 20, 24),
            children: [
              const ChildSwitcher(),
              const SizedBox(height: 12),
              if (child == null)
                const SizedBox.shrink()
              else if (rc == null)
                _NotReleased(termLabel: p.term?.label ?? '')
              else ...[
                _ReportCard(rc: rc, studentShort: child.shortName, house: child.house),
                const SizedBox(height: 12),
                Row(
                  children: [
                    Expanded(
                      child: FilledButton.icon(
                        onPressed: rc.pdfUrl == null
                            ? null
                            : () => launchUrl(Uri.parse(rc.pdfUrl!), mode: LaunchMode.externalApplication),
                        icon: const Icon(Icons.picture_as_pdf_outlined, size: 18),
                        label: const Text('Download PDF'),
                      ),
                    ),
                    const SizedBox(width: 10),
                    Expanded(
                      child: OutlinedButton.icon(
                        onPressed: () => _share(context, rc, child.fullName),
                        icon: const Icon(Icons.ios_share_rounded, size: 18),
                        label: const Text('Share'),
                      ),
                    ),
                  ],
                ),
                if (rc.pdfUrl == null)
                  const Padding(
                    padding: EdgeInsets.only(top: 8),
                    child: Text(
                      'The signed PDF is generated by the school once the headteacher stamps the report.',
                      textAlign: TextAlign.center,
                      style: TextStyle(fontSize: 11, color: TgsColors.fg3),
                    ),
                  ),
              ],
            ],
          ),
        ),
      ],
    );
  }

  void _share(BuildContext context, ReportCard rc, String name) {
    // Native share sheet requires share_plus; use a summary snackbar until
    // the Android Intent is wired in the staff/production build.
    final avg = rc.results.isEmpty
        ? 0
        : (rc.results.fold<int>(0, (a, r) => a + r.total) / rc.results.length).round();
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text('$name · ${rc.termLabel} · ${rc.positionLabel} · avg $avg/100')),
    );
  }
}

