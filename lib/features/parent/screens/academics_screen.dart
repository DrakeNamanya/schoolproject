class _Grid extends StatelessWidget {
  const _Grid(this.rows);
  final List<SubjectResult> rows;

  static const _h = TextStyle(
    fontSize: 10,
    fontWeight: FontWeight.w700,
    letterSpacing: .8,
    color: TgsColors.fg3,
  );

  @override
  Widget build(BuildContext context) {
    return Table(
      columnWidths: const {
        0: FlexColumnWidth(2.2),
        1: FlexColumnWidth(1),
        2: FlexColumnWidth(1),
        3: FlexColumnWidth(.9),
      },
      border: const TableBorder(
        horizontalInside: BorderSide(color: TgsColors.border1),
        bottom: BorderSide(color: TgsColors.border1),
        top: BorderSide(color: TgsColors.border1),
      ),
      children: [
        TableRow(
          decoration: const BoxDecoration(color: TgsColors.paper),
          children: [
            _cell(const Text('SUBJECT', style: _h)),
            _cell(const Text('CAT', style: _h), right: true),
            _cell(const Text('EXAM', style: _h), right: true),
            _cell(const Text('GRADE', style: _h), center: true),
          ],
        ),
        for (final r in rows)
          TableRow(
            children: [
              _cell(Text(r.subject, style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600))),
              _cell(Text('${r.catScore}/${r.catOutOf}', style: _mono), right: true),
              _cell(Text('${r.examScore}/${r.examOutOf}', style: _mono), right: true),
              _cell(_GradeChip(r.grade), center: true),
            ],
          ),
      ],
    );
  }

  static const _mono = TextStyle(
    fontFamily: TgsFonts.mono,
    fontSize: 12,
    fontWeight: FontWeight.w500,
    color: TgsColors.fg2,
  );

  Widget _cell(Widget child, {bool right = false, bool center = false}) => Padding(
    padding: const EdgeInsets.symmetric(vertical: 8, horizontal: 4),
    child: Align(
      alignment: center
          ? Alignment.center
          : right
          ? Alignment.centerRight
          : Alignment.centerLeft,
      child: child,
    ),
  );
}

class _GradeChip extends StatelessWidget {
  const _GradeChip(this.g);
  final String g;
  @override
  Widget build(BuildContext context) {
    final good = g.startsWith('D');
    final ok = g.startsWith('C');
    final (bg, fg) = good
        ? (TgsColors.maroon500, Colors.white)
        : ok
        ? (TgsColors.navy50, TgsColors.navy600)
        : (TgsColors.dangerBg, TgsColors.brick600);
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
      decoration: BoxDecoration(color: bg, borderRadius: BorderRadius.circular(6)),
      child: Text(
        g,
        style: TextStyle(fontFamily: TgsFonts.mono, fontSize: 12, fontWeight: FontWeight.w600, color: fg),
      ),
    );
  }
}
